"""Validate private QoL Toolkit exports and generate the public Lua table."""

import argparse
from contextlib import closing
from itertools import groupby
from pathlib import Path
import re
import sqlite3
from statistics import median
import sys
from tempfile import NamedTemporaryFile


MAX_EXPORT_BYTES = 8 * 1024 * 1024
POSITIVE_ID = r"[1-9][0-9]{0,9}"
RECORD = re.compile(rf"({POSITIVE_ID}),([01]),({POSITIVE_ID}(?:>{POSITIVE_ID}){{1,31}}),([0-9]{{1,4}})")
SCHEMA = """
    CREATE TABLE IF NOT EXISTS measurements (
        contributor TEXT NOT NULL,
        build INTEGER NOT NULL,
        speed INTEGER NOT NULL,
        route TEXT NOT NULL,
        seconds INTEGER NOT NULL,
        PRIMARY KEY (contributor, build, speed, route)
    )
"""


def read_export(payload):
    if len(payload) > MAX_EXPORT_BYTES:
        raise ValueError("Flight export is too large.")
    lines = payload.decode("ascii").strip().splitlines()
    if not lines or lines[0] != "QTF1" or len(lines) == 1:
        raise ValueError("Expected a QTF1 export with at least one measurement.")
    records = {}
    for number, line in enumerate(lines[1:], start=2):
        match = RECORD.fullmatch(line)
        if match is None:
            raise ValueError(f"Invalid measurement on line {number}.")
        build, speed, route, duration = match.groups()
        nodes = [int(node) for node in route.split(">")]
        seconds = int(duration)
        if int(build) > 2147483647 or max(nodes) > 2147483647 or len(set(nodes)) != len(nodes) or not 5 <= seconds <= 1800:
            raise ValueError(f"Out-of-range measurement on line {number}.")
        key = (int(build), int(speed), route)
        if key in records and records[key] != seconds:
            raise ValueError(f"Conflicting times for the same route on line {number}.")
        records[key] = seconds
    return records


def receive(db, contributor, records):
    if re.fullmatch(r"[a-z0-9][a-z0-9_-]{0,63}", contributor) is None:
        raise ValueError("Use a stable private contributor alias (a-z, 0-9, _, -).")
    with db:
        db.execute(SCHEMA)
        db.executemany(
            """
            INSERT INTO measurements (contributor, build, speed, route, seconds) VALUES (?, ?, ?, ?, ?)
            ON CONFLICT (contributor, build, speed, route) DO UPDATE SET seconds = excluded.seconds
            """,
            ((contributor, *key, seconds) for key, seconds in records.items()),
        )


def validated_times(db):
    rows = db.execute("SELECT build, speed, route, seconds FROM measurements ORDER BY build, speed, route")
    for (build, speed, route), group in groupby(rows, key=lambda row: row[:3]):
        values = [row[3] for row in group]
        if len(values) < 3:
            continue
        center = median(values)
        tolerance = max(3, center * 0.03)
        matching = [seconds for seconds in values if abs(seconds - center) <= tolerance]
        if len(matching) >= 3 and len(matching) * 2 > len(values):
            yield f"{build},{speed},{route}", int(median(matching) + 0.5)


def write_lua(output, times):
    if any(RECORD.fullmatch(f"{key},{seconds}") is None for key, seconds in times):
        raise ValueError("Invalid generated record. Check the private database.")
    lines = [
        "-- Generated by docs/flight_contributions.py from validated community measurements.",
        "local _, ns = ...",
        "ns.FlightTimesData = {",
        *(f'    ["{key}"] = {seconds},' for key, seconds in times),
        "}",
    ]
    with NamedTemporaryFile(mode="w", encoding="ascii", newline="\n", dir=output.parent, delete=False) as temp:
        temporary = Path(temp.name)
        temp.write("\n".join(lines) + "\n")
    try:
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=Path, required=True, help="Private SQLite file outside the repository")
    commands = parser.add_subparsers(dest="command", required=True)
    intake = commands.add_parser("receive", help="Read one contribution from a file or standard input")
    intake.add_argument("contributor", help="Stable alias assigned privately by the maintainer")
    intake.add_argument("file", type=Path, nargs="?")
    generate = commands.add_parser("build", help="Generate the Lua table from validated contributions")
    generate.add_argument("--output", type=Path, default=root / "Modules/FlightTimesData.lua")
    args = parser.parse_args()

    try:
        if args.database.resolve().is_relative_to(root):
            raise ValueError("Keep the private database outside the repository.")
        if args.command == "receive":
            if args.file is None:
                payload = sys.stdin.buffer.read(MAX_EXPORT_BYTES + 1)
            else:
                with args.file.open("rb") as source:
                    payload = source.read(MAX_EXPORT_BYTES + 1)
            records = read_export(payload)
            with closing(sqlite3.connect(args.database)) as db:
                receive(db, args.contributor, records)
            print(f"Imported {len(records)} measurement(s).")
        else:
            if not args.database.is_file():
                raise ValueError("Private database not found.")
            if args.output.resolve() == args.database.resolve():
                raise ValueError("The output must differ from the private database.")
            with closing(sqlite3.connect(args.database)) as db:
                times = list(validated_times(db))
            write_lua(args.output, times)
            print(f"Generated {len(times)} validated duration(s).")
    except (OSError, ValueError, sqlite3.Error) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
